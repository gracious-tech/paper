
// Compile the doc-domain catalogs (typst/locales/*.json) into typst/src/generated/doc_strings.ts,
// so the typst package carries them in its own JS for every consumer — the app's main thread,
// the server and the cover renderer — with no loader to wire up in each. Run by .bin/i18n_sync,
// .bin/i18n_apply and .bin/build_typst; .bin/i18n_check fails if the module is out of date.
// Every locale is bundled, so this suits the handful of short strings a document prints; if it
// ever grows to hundreds of locales, load them per language instead.
// Usage: node app/i18n/gen_doc.ts

import {readFileSync, writeFileSync, existsSync, mkdirSync} from 'node:fs'
import {join, dirname} from 'node:path'
import {fileURLToPath} from 'node:url'

import {DOMAINS, TYPST_DIR, read_meta, read_catalog, locale_path, rel}
    from './lib.ts'

// Where the compiled module goes
export const DOC_MODULE_PATH = join(TYPST_DIR, 'src', 'generated', 'doc_strings.ts')


// The module's full source, from the catalogs as they are on disk now
export function doc_module_source():string {
    const domain = DOMAINS.doc
    const source = read_catalog(locale_path(domain, domain.source))
    const translations:Record<string, Record<string, string>> = {}
    for (const loc of read_meta(domain).targets){
        const catalog = read_catalog(locale_path(domain, loc))
        if (Object.keys(catalog).length){
            translations[loc] = catalog
        }
    }
    const indent = (value:unknown):string => JSON.stringify(value, null, 4)
    return `// AUTO-GENERATED by app/i18n/gen_doc.ts from typst/locales/ — do not edit by hand.
// Translate through .bin/i18n_job / .bin/i18n_apply (see .claude/skills/translate), which
// regenerate this file.


// The English source strings, which define every key
export const DOC_SOURCE = ${indent(source)} as const


// Translations by fetch.bible language code; a key a translation lacks falls back to DOC_SOURCE
export const DOC_TRANSLATIONS:Record<string, Partial<Record<keyof typeof DOC_SOURCE, string>>> = ${
    indent(translations)}
`
}


// Whether the module on disk matches the catalogs (for .bin/i18n_check)
export function doc_module_current():boolean {
    return existsSync(DOC_MODULE_PATH)
        && readFileSync(DOC_MODULE_PATH, 'utf8') === doc_module_source()
}


// (Re)write the module from the catalogs
export function write_doc_module():void {
    mkdirSync(dirname(DOC_MODULE_PATH), {recursive: true})
    writeFileSync(DOC_MODULE_PATH, doc_module_source())
}


// Run directly: regenerate and say so
if (process.argv[1] === fileURLToPath(import.meta.url)){
    write_doc_module()
    console.log(`wrote ${rel(DOC_MODULE_PATH)}`)
}
